function isLocale(value: string | null): value is Locale {
  return value === 'en' || value === 'zh-CN' || value === 'fr'
}

function initialLocale(): Locale {
  try {
    const stored = window.localStorage.getItem(storageKey)
    if (isLocale(stored)) return stored
  } catch {
    // A blocked storage area should not stop the monitor from rendering.
  }

  const preferred = navigator.language.toLowerCase()
  if (preferred.startsWith('zh')) return 'zh-CN'
  if (preferred.startsWith('fr')) return 'fr'
  return 'en'
}

function interpolate(message: string, values?: MessageValues): string {
  if (!values) return message
  return message.replace(/\{(\w+)\}/g, (token, key) => String(values[key] ?? token))
}

interface I18nContextValue {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: string, values?: MessageValues) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(initialLocale)

  useEffect(() => {
    document.documentElement.lang = locale
    try {
      window.localStorage.setItem(storageKey, locale)
    } catch {
      // The selected language remains active for the current session.
    }
  }, [locale])

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale,
    t: (key, values) => interpolate(messages[locale][key] ?? messages.en[key] ?? key, values)
  }), [locale])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext)
  if (!context) throw new Error('I18nProvider is missing from the renderer tree.')
  return context
}
